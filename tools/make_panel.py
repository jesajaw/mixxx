#!/usr/bin/env python3
"""Generates the Mixxx mapping of the touch panel from panel/protocol.py.

  controllers/DJS-Touch-Panel.midi.xml        which MIDI message calls DJSPanel.input
  controllers/DJS-Touch-Panel-scripts.js      panel/mapping.template.js + the protocol table

  python3 tools/make_panel.py           write both files
  python3 tools/make_panel.py --check   exit 1 if the committed files are not up to date (used by `make check`)
"""
import json
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "panel"))
sys.dont_write_bytecode = True
import protocol as P  # noqa: E402

OUT_XML = ROOT / "controllers" / "DJS-Touch-Panel.midi.xml"
OUT_JS = ROOT / "controllers" / "DJS-Touch-Panel-scripts.js"
TEMPLATE = ROOT / "panel" / "mapping.template.js"


def _table():
    keep = ("id", "kind", "num", "mixxx", "feedback")
    return [{k: c[k] for k in keep} for c in P.CONTROLS]


def build_js():
    consts = (
        f"DJSPanel.NOTE_ON_IN = {P.NOTE_ON_IN};   // 0x{P.NOTE_ON_IN:02X}\n"
        f"DJSPanel.CC_IN = {P.CC_IN};        // 0x{P.CC_IN:02X}\n"
        f"DJSPanel.NOTE_ON_OUT = {P.NOTE_ON_OUT};  // 0x{P.NOTE_ON_OUT:02X}\n"
        f"DJSPanel.CC_OUT = {P.CC_OUT};       // 0x{P.CC_OUT:02X}\n"
        f"DJSPanel.JOG_TICKS_PER_REV = {P.JOG_TICKS_PER_REV};\n"
    )
    text = TEMPLATE.read_text(encoding="utf8")
    table = json.dumps(_table(), indent=1, sort_keys=True)
    assert text.count("/*@PROTOCOL@*/ []") == 1 and text.count("/*@CONSTANTS@*/") == 1
    return text.replace("/*@PROTOCOL@*/ []", table).replace("/*@CONSTANTS@*/", consts)


def build_xml():
    rows = []

    def control(status, num, group):
        rows.append(
            "      <control>\n"
            f"        <group>{escape(group)}</group>\n"
            "        <key>DJSPanel.input</key>\n"
            f"        <status>0x{status:02X}</status>\n"
            f"        <midino>0x{num:02X}</midino>\n"
            "        <options>\n          <script-binding/>\n        </options>\n"
            "      </control>")

    for c in P.CONTROLS:
        status = P.midi_in_status(c)
        if status is None:
            continue
        group = (c["mixxx"] or {}).get("group", "[Master]")
        control(status, c["num"], group)
        if c["kind"] == "abs14":
            control(status, c["num"] + 32, group)
    return (
        "<?xml version='1.0' encoding='utf-8'?>\n"
        "<!-- GENERATED by tools/make_panel.py from panel/protocol.py - do not edit by hand. -->\n"
        '<MixxxControllerPreset mixxxVersion="2.1" schemaVersion="1">\n'
        "  <info>\n"
        "    <name>DJS Touch Panel</name>\n"
        "    <author>DJS</author>\n"
        "    <description>Virtual DJ controller: a browser touch panel (decks, jog, EQ, crossfader, hotcues, loops, "
        "library, Auto DJ) that talks to Mixxx over a virtual MIDI port. Needs panel/server.py. "
        "Panel to Mixxx: MIDI channel 1, Mixxx to panel: channel 2.</description>\n"
        "  </info>\n"
        '  <controller id="DJSPanel">\n'
        "    <scriptfiles>\n"
        '      <file filename="DJS-Touch-Panel-scripts.js" functionprefix="DJSPanel"/>\n'
        "    </scriptfiles>\n"
        "    <controls>\n" + "\n".join(rows) + "\n    </controls>\n"
        "    <outputs/>\n"
        "  </controller>\n"
        "</MixxxControllerPreset>\n"
    )


def main(argv):
    wanted = {OUT_XML: build_xml(), OUT_JS: build_js()}
    if "--check" in argv:
        stale = [p.name for p, t in wanted.items() if not p.exists() or p.read_text(encoding="utf8") != t]
        if stale:
            print("out of date (run: python3 tools/make_panel.py): " + ", ".join(stale))
            return 1
        print("touch panel mapping is up to date")
        return 0
    for p, t in wanted.items():
        p.write_text(t, encoding="utf8")
        print("written", p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
