#!/usr/bin/env python3
"""Generates the "Studio" color scheme from LateNight's PaleMoon scheme.

What happens:
  * skins/StudioDeck/style_palemoon.qss  ->  style_studio.qss
  * skins/StudioDeck/palemoon/            ->  skins/StudioDeck/studio/  (SVGs recolored)

Only colors written as hex values in the files are recolored:
  * neutral greys get a cool blue tint (chassis look)
  * teal/blue hues move to indigo
  * everything else (amber LEDs, green, red ...) stays unchanged

The values live in tools/palette.json. The script is idempotent: the studio/
folder is regenerated on every run.
"""
import colorsys
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIN = ROOT / "skins" / "StudioDeck"
PALETTE = json.loads((Path(__file__).parent / "palette.json").read_text())

HEX = re.compile(r"(?<!url\()#(?:[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b")
RGBA = re.compile(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(,\s*[\d.]+\s*)?\)")


def _recolor(r, g, b):
    """r,g,b in 0..255 -> new r,g,b (ints)."""
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    if l < 0.02 or l > 0.93:
        return r, g, b                       # pure black/white stays
    if s < 0.15:                             # neutral grey -> chassis tint
        fade = 1.0 if l <= 0.30 else max(0.15, 1.0 - (l - 0.30) * 1.7)
        h = PALETTE["chassis_hue"] / 360
        s = PALETTE["chassis_saturation"] * fade
    else:
        lo, hi = PALETTE["accent_from_range"]
        if lo <= h * 360 <= hi:              # Teal/Blau -> Indigo
            h = PALETTE["accent_hue"] / 360
            s = min(s, PALETTE["accent_saturation_cap"])
            l = min(0.9, l + PALETTE["accent_lightness_boost"])
        else:
            return r, g, b
    nr, ng, nb = colorsys.hls_to_rgb(h, l, s)
    return round(nr * 255), round(ng * 255), round(nb * 255)


def _hex(m):
    t = m.group(0)[1:]
    if len(t) == 3:
        t = "".join(c * 2 for c in t)
    r, g, b = (int(t[i:i + 2], 16) for i in (0, 2, 4))
    return "#%02x%02x%02x" % _recolor(r, g, b)


def _rgba(m):
    r, g, b = (int(m.group(i)) for i in (1, 2, 3))
    nr, ng, nb = _recolor(r, g, b)
    tail = m.group(4) or ""
    fn = "rgba" if tail else "rgb"
    return f"{fn}({nr}, {ng}, {nb}{tail})"


def recolor_text(text):
    return RGBA.sub(_rgba, HEX.sub(_hex, text))


def recolor_qss(text):
    """Recolor only inside {...} so that selectors like #abc stay intact."""
    out, depth = [], 0
    for tok in re.split(r"([{}])", text):
        if tok == "{":
            depth += 1
            out.append(tok)
        elif tok == "}":
            depth = max(0, depth - 1)
            out.append(tok)
        else:
            out.append(recolor_text(tok) if depth > 0 else tok)
    return "".join(out)


def main():
    src_qss = SKIN / "style_palemoon.qss"
    dst_qss = SKIN / "style_studio.qss"
    text = src_qss.read_text(encoding="utf8")
    text = recolor_qss(text).replace("skins:StudioDeck/palemoon/", "skins:StudioDeck/studio/")
    text = text.replace("PaleMoon theme", "Studio theme (generated by tools/make_scheme.py from PaleMoon)", 1)
    dst_qss.write_text(text, encoding="utf8")

    src_dir, dst_dir = SKIN / "palemoon", SKIN / "studio"
    if dst_dir.exists():
        shutil.rmtree(dst_dir)
    shutil.copytree(src_dir, dst_dir)
    n = 0
    for svg in dst_dir.rglob("*.svg"):
        raw = svg.read_text(encoding="utf8", errors="surrogateescape")
        new = recolor_text(raw)
        if new != raw:
            svg.write_text(new, encoding="utf8", errors="surrogateescape")
            n += 1
    print(f"style_studio.qss written, {n} SVGs recolored -> {dst_dir.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
